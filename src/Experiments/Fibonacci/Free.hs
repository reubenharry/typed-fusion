--------------------------------------------------------------------------------
-- Free monoidal category
--------------------------------------------------------------------------------

-- | Free monoidal category generated by Fib theory morphisms.
--
-- Objects remain @FibObj@ trees. Morphisms are syntax; equality is syntactic.
data FreeFib :: FibObj -> FibObj -> Type where
  IdF :: Object Fib a => FreeFib a a
  CompF
    :: (Object Fib a, Object Fib b, Object Fib c)
    => FreeFib b c
    -> FreeFib a b
    -> FreeFib a c
  TensorF
    :: ( Object Fib a
       , Object Fib b
       , Object Fib c
       , Object Fib d
       , Object Fib (Tensor a c)
       , Object Fib (Tensor b d)
       )
    => FreeFib a b
    -> FreeFib c d
    -> FreeFib (Tensor a c) (Tensor b d)
  -- Generators
  CupF :: FreeFib 'One TauTau
  CapF :: FreeFib TauTau 'One
  FuseF :: FreeFib TauTau OnePlusTau
  SplitF :: FreeFib OnePlusTau TauTau
  AssocF
    :: ( Object Fib a
       , Object Fib b
       , Object Fib c
       , Object Fib (Tensor a b)
       , Object Fib (Tensor b c)
       , Object Fib (Tensor (Tensor a b) c)
       , Object Fib (Tensor a (Tensor b c))
       )
    => FreeFib (Tensor (Tensor a b) c) (Tensor a (Tensor b c))
  DisassocF
    :: ( Object Fib a
       , Object Fib b
       , Object Fib c
       , Object Fib (Tensor a b)
       , Object Fib (Tensor b c)
       , Object Fib (Tensor (Tensor a b) c)
       , Object Fib (Tensor a (Tensor b c))
       )
    => FreeFib (Tensor a (Tensor b c)) (Tensor (Tensor a b) c)
  BraidF
    :: ( Object Fib a
       , Object Fib b
       , Object Fib (Tensor a b)
       , Object Fib (Tensor b a)
       )
    => FreeFib (Tensor a b) (Tensor b a)
  IdlF
    :: (Object Fib a, Object Fib 'One, Object Fib (Tensor 'One a))
    => FreeFib (Tensor 'One a) a
  IdrF
    :: (Object Fib a, Object Fib 'One, Object Fib (Tensor a 'One))
    => FreeFib (Tensor a 'One) a
  CoidlF
    :: (Object Fib a, Object Fib 'One, Object Fib (Tensor 'One a))
    => FreeFib a (Tensor 'One a)
  CoidrF
    :: (Object Fib a, Object Fib 'One, Object Fib (Tensor a 'One))
    => FreeFib a (Tensor a 'One)
  -- | Opaque leaf: concrete @Fib@ drawn as a labeled box.
  BoxF :: String -> Fib a b -> FreeFib a b

--------------------------------------------------------------------------------
-- Semantics: Free → Fib
--------------------------------------------------------------------------------

-- | Unique monoidal functor extending the generator interpretation.
eval :: forall a b. FreeFib a b -> Fib a b
eval IdF = id
eval (CompF g f) = eval g . eval f
eval (TensorF f g) = bimap (eval f) (eval g)
eval CupF = cup
eval CapF = cap
eval FuseF = fuse
eval SplitF = split
eval AssocF = associate
eval DisassocF = disassociate
eval BraidF = braid
eval IdlF = idl
eval IdrF = idr
eval CoidlF = coidl
eval CoidrF = coidr
eval (BoxF _ m) = m

--------------------------------------------------------------------------------
-- Category / monoidal structure (syntax)
--------------------------------------------------------------------------------

instance Category FreeFib where
  type Object FreeFib a = Object Fib a

  id :: forall a. Object FreeFib a => FreeFib a a
  id = IdF

  (.)
    :: forall a b c
     . (Object FreeFib a, Object FreeFib b, Object FreeFib c)
    => FreeFib b c
    -> FreeFib a b
    -> FreeFib a c
  (.) = CompF

instance PFunctor Tensor FreeFib FreeFib where
  first
    :: forall a b c
     . ( Object FreeFib a
       , Object FreeFib b
       , Object FreeFib c
       , Object FreeFib (Tensor a c)
       , Object FreeFib (Tensor b c)
       )
    => FreeFib a b
    -> FreeFib (Tensor a c) (Tensor b c)
  first f = TensorF f (id :: FreeFib c c)

instance QFunctor Tensor FreeFib FreeFib where
  second
    :: forall a b c
     . ( Object FreeFib a
       , Object FreeFib b
       , Object FreeFib c
       , Object FreeFib (Tensor c a)
       , Object FreeFib (Tensor c b)
       )
    => FreeFib a b
    -> FreeFib (Tensor c a) (Tensor c b)
  second g = TensorF (id :: FreeFib c c) g

instance Bifunctor Tensor FreeFib FreeFib FreeFib where
  bimap
    :: forall a b c d
     . ( Object FreeFib a
       , Object FreeFib b
       , Object FreeFib c
       , Object FreeFib d
       , Object FreeFib (Tensor a c)
       , Object FreeFib (Tensor b d)
       )
    => FreeFib a b
    -> FreeFib c d
    -> FreeFib (Tensor a c) (Tensor b d)
  bimap = TensorF

instance Associative FreeFib Tensor where
  associate = AssocF
  disassociate = DisassocF

instance Monoidal FreeFib Tensor where
  type Id FreeFib Tensor = 'One
  idl = IdlF
  idr = IdrF
  coidl = CoidlF
  coidr = CoidrF

instance Braided FreeFib Tensor where
  braid = BraidF

--------------------------------------------------------------------------------
-- Gallery (shared by diagrams exe + computation smoke checks)
--------------------------------------------------------------------------------

exCup :: FreeFib 'One TauTau
exCup = CupF

exCap :: FreeFib TauTau 'One
exCap = CapF

-- | @cap ∘ cup : 𝟙 → 𝟙@ (snake scalar @φ@ under @eval@).
exSnake :: FreeFib 'One 'One
exSnake = CapF . CupF

exFuse :: FreeFib TauTau OnePlusTau
exFuse = FuseF

exSplit :: FreeFib OnePlusTau TauTau
exSplit = SplitF

-- | Associator @(τ⊗τ)⊗τ → τ⊗(τ⊗τ)@.
exFMove :: FreeFib (Tensor TauTau 'Tau) (Tensor 'Tau TauTau)
exFMove = AssocF

exFMoveInv :: FreeFib (Tensor 'Tau TauTau) (Tensor TauTau 'Tau)
exFMoveInv = DisassocF

-- | Braiding @τ⊗τ → τ⊗τ@.
exRMove :: FreeFib TauTau TauTau
exRMove = BraidF

-- | Yank @τ → τ@: @ρ ∘ (id ⊗ cap) ∘ F ∘ (cup ⊗ id) ∘ λ⁻¹@.
exYank :: FreeFib 'Tau 'Tau
exYank =
  IdrF
    . TensorF (id :: FreeFib 'Tau 'Tau) CapF
    . AssocF
    . TensorF CupF (id :: FreeFib 'Tau 'Tau)
    . CoidlF
